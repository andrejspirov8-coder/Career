function summary(row: OpportunityRow): OpportunitySummary {
  return {
    opportunity_id: row.opportunity_id,
    source: row.source,
    source_url: row.source_url,
    source_kind: row.source_kind,
    title: row.title,
    company: row.company,
    location: row.location,
    location_eligibility: row.location_eligibility,
    deadline: row.deadline,
    first_seen_at: row.first_seen_at,
    source_updated_at: row.source_updated_at,
    live_status: row.live_status,
    live_checked_at: row.live_checked_at,
    live_check_note: row.live_check_note,
    likely_closed: row.likely_closed,
    status: row.status,
    stage: row.status === 'apply_ready' ? 'pack_ready' : 'review',
    next_action: row.next_action,
    has_pack: Boolean(row.pack),
    evidence: {
      risk_flags: row.evidence.risk_flags,
      confidence: row.evidence.confidence,
      blockers: row.evidence.risk_flags.includes('watchlist_only') ? [] : row.evidence.risk_flags,
      warnings: [],
      info: row.evidence.risk_flags.includes('watchlist_only') ? ['watchlist_only'] : [],
    },
    match: row.match
      ? {
          best_variant: row.match.best_variant,
          score: row.match.score,
          fit_score: row.match.fit_score,
          cv_score: row.match.cv_score,
          role_track: row.match.role_track,
          confidence: row.match.confidence,
        }
      : null,
    preference: {
      eligible: true,
      score: row === readyRow ? 6 : 0,
      reasons: row === readyRow ? ['Matches your target role: retail operations'] : ['Recommended from current evidence'],
      flags: [],
    },
  }
}

